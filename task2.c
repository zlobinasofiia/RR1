/**
 * @file task1.c
 * @brief Обчислення суми скінченного математичного ряду.
 * @details Реалізація розрахунку суми ряду S без використання
 *          вбудованих математичних функцій (зокрема pow()).
 */

#include <stdio.h>
#include <windows.h>

/**
 * @brief Головна точка входу в програму (Завдання №1).
 * @return Код завершення програми (0 — успішно).
 */
int main() {
    // Налаштування таблиці символів консолі Windows для коректного відображення кирилиці (CP1251)
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    double a; // Змінна основи (арифметичний параметр)
    int N;    // Кількість ітерацій (верхня межа підсумовування)

    printf("=== Завдання №1: Обчислення суми ряду ===\n");

    /* -----------------------------------------------------------------
     * Блок введення та валідації початкових даних
     * ----------------------------------------------------------------- */

    // Введення параметра 'a' з контролем типу та діапазону (a >= 0)
    do {
        printf("Введіть значення a (a >= 0): ");
        if (scanf("%lf", &a) != 1 || a < 0) {
            printf("Помилка! Значення 'a' має бути дійсним числом >= 0.\n");
            while (getchar() != '\n'); // Очищення буфера введення від некоректних символів
        } else {
            break;
        }
    } while (1);

    // Введення параметра 'N' з контролем типу та діапазону (N >= 1)
    do {
        printf("Введіть ціле значення N (N >= 1): ");
        if (scanf("%d", &N) != 1 || N < 1) {
            printf("Помилка! Значення 'N' має бути цілим числом >= 1.\n");
            while (getchar() != '\n'); // Очищення буфера введення
        } else {
            break;
        }
    } while (1);

    /* -----------------------------------------------------------------
     * Обчислювальний блок
     * ----------------------------------------------------------------- */

    double S = 1.0;            // Початкове значення суми ряду (S_0 = 1)
    double current_a_pow = 1.0; // Акумулятор степеня: зберігає значення a^n
    int sign = 1;              // Знаковий множник: (-1)^(n-1), починаючи з '+' при n = 1

    // Обчислення членів ряду в циклі
    for (int n = 1; n <= N; n++) {
        // Рекурентне обчислення степеня a^n без використання pow()
        current_a_pow *= a;

        // Обчислення поточного члена ряду: term_n = (-1)^(n-1) * (a^n / (a + n))
        double term = sign * (current_a_pow / (a + n));

        // Накопичення суми
        S += term;

        // Інверсія знака для наступного доданка
        sign = -sign;
    }

    // Виведення фінального результату з точністю до 6 знаків після коми
    printf("\nРезультат обчислення суми S = %.6lf\n", S);

    return 0;
}
